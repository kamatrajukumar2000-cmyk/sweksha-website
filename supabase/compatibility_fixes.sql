-- Reviews table already exists in the current project; create only if missing
-- and add no destructive changes. Existing columns name/rating/review/status are retained.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  rating integer not null,
  review text not null,
  status text not null default 'pending'
);

alter table public.reviews add column if not exists name text;
alter table public.reviews add column if not exists rating integer;
alter table public.reviews add column if not exists review text;
alter table public.reviews add column if not exists status text not null default 'pending';
alter table public.reviews add column if not exists created_at timestamptz not null default now();

